// The SSP as a pure outline: what the document says, in the order it says it. The render turns
// it into a .docx; nothing here reads a database, a clock or a file. The sections follow the
// OSCAL SSP shape: system characteristics, then the implementation of each requirement.
import type { Catalog, Family, ObjectiveId, Requirement } from '@rampart/catalog';
import { REGULATION } from '@rampart/rules/poam';
import {
  ASSESSMENT_TYPE_LABELS,
  CONDITIONAL_STATUS_LABELS,
  OBJECTIVE_STATUS_LABELS,
  REQUIREMENT_NOT_APPLICABLE_LABEL,
  REQUIREMENT_STATUS_LABELS,
  SYSTEM_PROFILE_FIELDS,
  type AssessmentView,
  type EvidenceItem,
  type Policy,
  type PoamItem,
  type PoamView,
  type RequirementState,
  type SystemProfile,
} from '../src/contract';

/** Everything the SSP is built from: what the five api reads return, plus the catalog. */
export interface SspSource {
  catalog: Catalog;
  profile: SystemProfile;
  view: AssessmentView;
  poam: PoamView;
  policies: readonly Policy[];
  evidence: readonly EvidenceItem[];
}

/**
 * One piece of the document. Text may hold newlines; the render makes each line a paragraph and
 * drops the characters XML can't hold.
 */
export type SspBlock =
  | { kind: 'title'; text: string }
  | { kind: 'subtitle'; text: string }
  /** "Generated by <product> on <today>": the render fills it from its `generatedAt`. */
  | { kind: 'generated' }
  | { kind: 'heading'; level: 1 | 2 | 3; text: string }
  | { kind: 'paragraph'; text: string }
  /** `Label: value` on one line. */
  | { kind: 'field'; label: string; value: string }
  /** `Label:` on its own line, then the text. */
  | { kind: 'text'; label: string; text: string }
  /** `Label:` then one line per item, or `Label: <empty>` when there are none. */
  | { kind: 'list'; label: string; items: string[]; empty: string }
  | { kind: 'table'; columns: string[]; rows: string[][] };

export interface SspModel {
  blocks: SspBlock[];
}

export const SSP_SECTIONS = {
  characteristics: '1. System characteristics',
  summary: '2. Assessment summary',
  requirements: '3. Security requirements',
  poam: '4. Plan of action and milestones',
} as const;

const NOT_PROVIDED = 'Not provided';
const NONE_LINKED = 'None linked';

/** What each implementation level reads as; the partial level reads as its catalog label. */
const LEVEL_NOT_SET = 'Not set (worst case)';
const LEVEL_NONE = 'Not implemented';

type Outcome = AssessmentView['evaluation']['outcomes'][number];
type Owner = { displayName: string; active: boolean } | null;

function ownerName(owner: Owner): string {
  if (owner === null) return 'Unassigned';
  return owner.active ? owner.displayName : `${owner.displayName} (inactive)`;
}

/** The label a requirement's status reads as; a requirement whose objectives are all N/A reads Not Applicable. */
function statusLabel(outcome: Outcome | undefined): string {
  if (outcome === undefined) return REQUIREMENT_STATUS_LABELS.not_assessed;
  return outcome.allNa
    ? REQUIREMENT_NOT_APPLICABLE_LABEL
    : REQUIREMENT_STATUS_LABELS[outcome.status];
}

function titleBlocks(source: SspSource): SspBlock[] {
  const { assessment } = source.view;
  return [
    { kind: 'title', text: 'System Security Plan' },
    { kind: 'subtitle', text: source.profile.systemName ?? 'System not named' },
    { kind: 'generated' },
    { kind: 'field', label: 'Catalog version', value: assessment.catalogVersion },
    { kind: 'field', label: 'Regulation version', value: `${REGULATION.id}@${REGULATION.version}` },
    { kind: 'field', label: 'Assessment type', value: ASSESSMENT_TYPE_LABELS[assessment.type] },
  ];
}

function characteristicsBlocks(profile: SystemProfile): SspBlock[] {
  return [
    { kind: 'heading', level: 1, text: SSP_SECTIONS.characteristics },
    {
      kind: 'table',
      columns: ['Characteristic', 'Value'],
      rows: SYSTEM_PROFILE_FIELDS.map(({ key, label }) => [label, profile[key] ?? NOT_PROVIDED]),
    },
  ];
}

function scoreLine(score: AssessmentView['evaluation']['score']): string {
  if (score.kind === 'scored') return `SPRS ${String(score.score)} / ${String(score.max)}`;
  return `SPRS incomplete: ${score.prerequisites.join(', ')} must be Met`;
}

function summaryBlocks(source: SspSource): SspBlock[] {
  const { evaluation, closeout } = source.view;
  const counts = new Map<string, number>([
    [REQUIREMENT_STATUS_LABELS.met, 0],
    [REQUIREMENT_STATUS_LABELS.not_met, 0],
    [REQUIREMENT_NOT_APPLICABLE_LABEL, 0],
    [REQUIREMENT_STATUS_LABELS.not_assessed, 0],
  ]);
  const outcomes = new Map(evaluation.outcomes.map((o) => [o.requirementId, o]));
  for (const requirement of source.catalog.requirements) {
    const label = statusLabel(outcomes.get(requirement.id));
    counts.set(label, (counts.get(label) ?? 0) + 1);
  }
  const openItems = source.poam.items.filter((i) => i.status === 'open').length;
  return [
    { kind: 'heading', level: 1, text: SSP_SECTIONS.summary },
    { kind: 'paragraph', text: scoreLine(evaluation.score) },
    {
      kind: 'field',
      label: 'Conditional status',
      value: CONDITIONAL_STATUS_LABELS[evaluation.conditional.status],
    },
    ...(closeout === null
      ? []
      : ([
          {
            kind: 'field',
            label: 'Conditional Status Date',
            value: closeout.conditionalStatusDate,
          },
          { kind: 'field', label: 'Closeout deadline', value: closeout.deadline },
        ] as const)),
    {
      kind: 'table',
      columns: ['Requirement status', 'Requirements'],
      rows: [...counts].map(([label, count]) => [label, String(count)]),
    },
    { kind: 'field', label: 'Open POA&M items', value: String(openItems) },
  ];
}

/** What the requirement blocks look up, indexed once. */
interface Lookup {
  outcomes: ReadonlyMap<string, Outcome>;
  states: ReadonlyMap<string, RequirementState>;
  objectiveStatuses: ReadonlyMap<ObjectiveId, string>;
  openItems: ReadonlyMap<string, PoamItem>;
  policies: readonly Policy[];
  evidence: readonly EvidenceItem[];
}

function lookupOf(source: SspSource): Lookup {
  const { view } = source;
  return {
    outcomes: new Map(view.evaluation.outcomes.map((o) => [o.requirementId, o])),
    states: new Map(view.requirementStates.map((s) => [s.requirementId, s])),
    objectiveStatuses: new Map(
      view.objectiveResults.map((r) => [r.objectiveId, OBJECTIVE_STATUS_LABELS[r.status]]),
    ),
    openItems: new Map(
      source.poam.items.filter((i) => i.status === 'open').map((i) => [i.requirementId, i]),
    ),
    policies: source.policies,
    evidence: source.evidence,
  };
}

function levelLabel(requirement: Requirement, state: RequirementState | undefined): string | null {
  if (requirement.scoring.kind !== 'points' || requirement.scoring.partialCredit === null) {
    return null;
  }
  const level = state?.implementationLevel ?? null;
  if (level === null) return LEVEL_NOT_SET;
  return level === 'partial' ? requirement.scoring.partialCredit.label : LEVEL_NONE;
}

function requirementBlocks(requirement: Requirement, lookup: Lookup): SspBlock[] {
  const state = lookup.states.get(requirement.id);
  const level = levelLabel(requirement, state);
  const objectiveIds = new Set(requirement.objectives.map((o) => o.id));
  const item = lookup.openItems.get(requirement.id);
  return [
    { kind: 'heading', level: 3, text: requirement.id },
    { kind: 'paragraph', text: requirement.text },
    { kind: 'field', label: 'Status', value: statusLabel(lookup.outcomes.get(requirement.id)) },
    {
      kind: 'field',
      label: 'Points',
      value:
        requirement.scoring.kind === 'points' ? String(requirement.scoring.points) : 'Prerequisite',
    },
    ...(level === null
      ? []
      : ([{ kind: 'field', label: 'Implementation level', value: level }] as const)),
    { kind: 'field', label: 'Owner', value: ownerName(state?.owner ?? null) },
    {
      kind: 'text',
      label: 'Implementation statement',
      text: state?.implementationStatement ?? 'No implementation statement recorded.',
    },
    {
      kind: 'table',
      columns: ['ID', 'Objective', 'Status'],
      rows: requirement.objectives.map((o) => [
        o.id,
        o.text,
        lookup.objectiveStatuses.get(o.id) ?? OBJECTIVE_STATUS_LABELS.not_assessed,
      ]),
    },
    {
      kind: 'list',
      label: 'Policies',
      items: lookup.policies
        .filter((p) => p.requirementIds.includes(requirement.id))
        .map((p) => p.title),
      empty: NONE_LINKED,
    },
    {
      kind: 'list',
      label: 'Evidence',
      items: lookup.evidence
        .filter((e) => e.objectiveIds.some((id) => objectiveIds.has(id)))
        .map((e) => e.title),
      empty: NONE_LINKED,
    },
    ...(item === undefined
      ? []
      : ([
          { kind: 'field', label: 'Open POA&M item', value: `Due ${item.due}` },
          { kind: 'text', label: 'Plan', text: item.plan },
        ] as const)),
  ];
}

function familyHeading(family: Family): string {
  return `${family.nistSection} ${family.name} (${family.code})`;
}

function requirementsBlocks(source: SspSource): SspBlock[] {
  const lookup = lookupOf(source);
  const byFamily = new Map<string, Requirement[]>();
  for (const requirement of source.catalog.requirements) {
    const list = byFamily.get(requirement.family) ?? [];
    list.push(requirement);
    byFamily.set(requirement.family, list);
  }
  return [
    { kind: 'heading', level: 1, text: SSP_SECTIONS.requirements },
    ...source.catalog.families.flatMap((family): SspBlock[] => [
      { kind: 'heading', level: 2, text: familyHeading(family) },
      ...(byFamily.get(family.code) ?? []).flatMap((r) => requirementBlocks(r, lookup)),
    ]),
  ];
}

function poamBlocks(poam: PoamView): SspBlock[] {
  const heading: SspBlock = { kind: 'heading', level: 1, text: SSP_SECTIONS.poam };
  if (poam.items.length === 0) {
    return [heading, { kind: 'paragraph', text: 'No POA&M items recorded.' }];
  }
  return [
    heading,
    {
      kind: 'table',
      columns: ['Requirement', 'Status', 'Due', 'Plan', 'Milestones', 'Owner', 'Closed on'],
      rows: poam.items.map((item) => [
        item.requirementId,
        item.status === 'open' ? 'Open' : 'Closed',
        item.due,
        item.plan,
        String(item.milestones.length),
        ownerName(item.owner),
        item.closeout?.closedOn ?? 'Not closed',
      ]),
    },
  ];
}

/** The SSP outline: the title block, then the four sections in order. */
export function buildSspModel(source: SspSource): SspModel {
  return {
    blocks: [
      ...titleBlocks(source),
      ...characteristicsBlocks(source.profile),
      ...summaryBlocks(source),
      ...requirementsBlocks(source),
      ...poamBlocks(source.poam),
    ],
  };
}
