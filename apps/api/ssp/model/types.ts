// What the SSP is built from and what it is made of. Nothing here reads a database, a clock or a
// file: the api's routes read the sources, and the render turns the blocks into a .docx.
import type { Catalog } from '@rampart/catalog';
import type {
  AssessmentView,
  Asset,
  DiagramLink,
  DocumentControl,
  EvidenceItem,
  Policy,
  PoamView,
  ResponsibilityRow,
  RolesResponse,
  ServiceProvider,
  SspProfile,
  SystemProfile,
  SystemRole,
} from '../../src/contract';

/** This export's own record-of-changes entry, printed after the stored revisions. */
export interface SspExportEntry {
  date: string;
  description: string;
  madeBy: string;
}

/** Everything the SSP is built from: what the api's reads return, plus the catalog. */
export interface SspSource {
  catalog: Catalog;
  profile: SystemProfile;
  view: AssessmentView;
  poam: PoamView;
  policies: readonly Policy[];
  evidence: readonly EvidenceItem[];
  sspProfile: SspProfile;
  roles: readonly SystemRole[];
  roleTotals: RolesResponse['totals'];
  /** In api order: category, then name. */
  assets: readonly Asset[];
  providers: readonly ServiceProvider[];
  /** The matrix rows, one per requirement; rows with no party are left out of the document. */
  responsibilities: readonly ResponsibilityRow[];
  /** In api order: kind, then created. */
  diagrams: readonly DiagramLink[];
  documentControl: DocumentControl;
  /** The bytes of the links the route could read, by link ID. */
  images: ReadonlyMap<string, Uint8Array>;
  /** At most this many links are embedded; the rest are referenced. */
  maxEmbeddedImages: number;
  exportEntry: SspExportEntry | null;
}

/**
 * One piece of the document. Text may hold newlines; the render makes each line a paragraph and
 * drops the characters XML can't hold.
 */
export type SspBlock =
  | { kind: 'title'; text: string }
  | { kind: 'subtitle'; text: string }
  /** "Generated by <product> on <today>": the render fills it from its `generatedAt`. */
  | { kind: 'generated' }
  | { kind: 'heading'; level: 1 | 2 | 3; text: string }
  | { kind: 'paragraph'; text: string }
  /** `Label: value` on one line. */
  | { kind: 'field'; label: string; value: string }
  /** `Label:` on its own line, then the text. */
  | { kind: 'text'; label: string; text: string }
  /** `Label:` then one line per item, or `Label: <empty>` when there are none. */
  | { kind: 'list'; label: string; items: string[]; empty: string }
  | { kind: 'table'; columns: string[]; rows: string[][] }
  /** A picture, drawn at `width` x `height` pixels (96 dpi). */
  | {
      kind: 'image';
      data: Uint8Array;
      type: 'png' | 'jpg';
      width: number;
      height: number;
      altText: string;
    }
  /** `<name>, <title>`, then a signature line, then the date or a blank date line. */
  | { kind: 'signature'; name: string; title: string; date: string | null };

export interface SspModel {
  blocks: SspBlock[];
}
