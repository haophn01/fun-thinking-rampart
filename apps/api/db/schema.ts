/**
 * POA&M items. At most one open item per requirement (a partial unique index); closed items stay
 * as history, so a requirement that is Not Met again can get a new one. Never deleted.
 */
export const poamItem = sqliteTable(
  'poam_item',
  {
    /** A UUID, generated by the api. */
    id: text('id').primaryKey(),
    assessmentId: text('assessment_id')
      .notNull()
      .references(() => assessment.id),
    /** Catalog requirement ID, e.g. AC.L2-3.1.1. The api checks it against the catalog. */
    requirementId: text('requirement_id').notNull(),
    status: text('status', { enum: POAM_STATUSES }).notNull().default('open'),
    plan: text('plan').notNull(),
    /** YYYY-MM-DD. */
    due: text('due').notNull(),
    /** JSON list of `{ title, due, doneOn }` (contract `milestonesSchema`). */
    milestones: text('milestones').notNull().default('[]'),
    ownerUserId: text('owner_user_id').references(() => user.id),
    // The closeout: all null while open; closed_on, confirmed_by and closed_by set once closed.
    /** YYYY-MM-DD. */
    closedOn: text('closed_on'),
    closeoutNote: text('closeout_note'),
    confirmedBy: text('confirmed_by', { enum: CLOSEOUT_CONFIRMERS }),
    c3paoName: text('c3pao_name'),
    closedBy: text('closed_by').references(() => user.id),
    createdBy: text('created_by')
      .notNull()
      .references(() => user.id),
    /** ISO timestamps from the api's clock. */
    createdAt: text('created_at').notNull(),
    updatedBy: text('updated_by')
      .notNull()
      .references(() => user.id),
    updatedAt: text('updated_at').notNull(),
  },
  (table) => [
    check('poam_item_status_check', sql`${table.status} in ('open', 'closed')`),
    check('poam_item_confirmed_by_check', sql`${table.confirmedBy} in ('organization', 'c3pao')`),
    check(
      'poam_item_closeout_check',
      sql`(${table.status} = 'open' and ${table.closedOn} is null and ${table.closeoutNote} is null
        and ${table.confirmedBy} is null and ${table.c3paoName} is null and ${table.closedBy} is null)
        or (${table.status} = 'closed' and ${table.closedOn} is not null
        and ${table.confirmedBy} is not null and ${table.closedBy} is not null)`,
    ),
    uniqueIndex('poam_item_open_requirement_unique')
      .on(table.assessmentId, table.requirementId)
      .where(sql`status = 'open'`),
  ],
);

