/** An ISO 8601 UTC timestamp with milliseconds, e.g. 2026-11-23T22:30:00.000Z. */
const isoNow = sql`(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))`;

/**
 * Text compared without case, so the unique index and every `email = ?` lookup treat
 * A@x.com and a@x.com as the same address.
 */
const nocaseText = customType<{ data: string }>({
  dataType: () => 'text COLLATE NOCASE',
});

export const assessment = sqliteTable(
  'assessment',
  {
    /** A UUID, generated by the api. */
    id: text('id').primaryKey(),
    type: text('type', { enum: ASSESSMENT_TYPES }).notNull().default('self'),
    /** YYYY-MM-DD, set when the assessment reaches Conditional status. */
    conditionalStatusDate: text('conditional_status_date'),
    /** `catalogKey(catalog)`, e.g. nist-800-171-r2@1.0.0. */
    catalogVersion: text('catalog_version').notNull(),
    createdAt: text('created_at').notNull().default(isoNow),
    updatedAt: text('updated_at').notNull().default(isoNow),
  },
  (table) => [check('assessment_type_check', sql`${table.type} in ('self', 'c3pao')`)],
);

/** People who sign in. Never deleted; `active = false` turns one off. */
export const user = sqliteTable(
  'user',
  {
    /** A UUID, generated by the api. */
    id: text('id').primaryKey(),
    /** Unique without case. The api stores it trimmed and lowercased. */
    email: nocaseText('email').notNull().unique('user_email_unique'),
    displayName: text('display_name').notNull(),
    role: text('role', { enum: ROLES }).notNull(),
    /** An Argon2id hash (`$argon2id$…`). Never returned, logged or audited. */
    passwordHash: text('password_hash').notNull(),
    active: integer('active', { mode: 'boolean' }).notNull().default(true),
    /** Consecutive failed sign-ins; reset by a success or when a lock ends. */
    failedSignIns: integer('failed_sign_ins').notNull().default(0),
    /** ISO timestamp; sign-in is refused while now < locked_until. */
    lockedUntil: text('locked_until'),
    createdAt: text('created_at').notNull().default(isoNow),
    updatedAt: text('updated_at').notNull().default(isoNow),
    // Migration 0006 (sec-auth). Rows from before it read false and null.
    /** Set for a temporary password: the next sign-in must choose a new one. */
    mustChangePassword: integer('must_change_password', { mode: 'boolean' })
      .notNull()
      .default(false),
    /** ISO timestamp of the last password set; null for passwords set before 0006. */
    passwordChangedAt: text('password_changed_at'),
    /** The TOTP secret, encrypted by the api (sec-mfa). Null until MFA is enrolled. */
    mfaSecretEnc: text('mfa_secret_enc'),
    /** The last TOTP time step accepted, so a code is never accepted twice (sec-mfa). */
    mfaLastStep: integer('mfa_last_step'),
    /** ISO timestamp; when MFA enrolment finished (sec-mfa). */
    mfaEnrolledAt: text('mfa_enrolled_at'),
  },
  (table) => [
    check('user_role_check', sql`${table.role} in ('admin', 'contributor')`),
    check('user_active_check', sql`${table.active} in (0, 1)`),
  ],
);

