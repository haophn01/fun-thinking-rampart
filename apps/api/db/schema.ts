// The SSP data tables (migration 0005). Rows of the collections are removed softly: the api sets
// `removed_at` and never deletes. Timestamps and `*_by` come from the api, so none has a default.

/** `created_by`, `created_at`, `updated_by`, `updated_at`: who made a row and last changed it. */
function stamps() {
  return {
    createdBy: text('created_by')
      .notNull()
      .references(() => user.id),
    /** ISO timestamps from the api's clock. */
    createdAt: text('created_at').notNull(),
    updatedBy: text('updated_by')
      .notNull()
      .references(() => user.id),
    updatedAt: text('updated_at').notNull(),
  };
}

/** A UUID generated by the api, and the assessment the row belongs to. */
function collectionKeys() {
  return {
    id: text('id').primaryKey(),
    assessmentId: text('assessment_id')
      .notNull()
      .references(() => assessment.id),
  };
}

