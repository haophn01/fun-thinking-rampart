import { sql } from 'drizzle-orm';
import {
  check,
  customType,
  index,
  integer,
  primaryKey,
  sqliteTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/sqlite-core';

export const ASSESSMENT_TYPES = ['self', 'c3pao'] as const;
export const ROLES = ['admin', 'contributor'] as const;
export const OBJECTIVE_STATUSES = ['met', 'not_met', 'na', 'not_assessed'] as const;
export const IMPLEMENTATION_LEVELS = ['none', 'partial'] as const;
export const POAM_STATUSES = ['open', 'closed'] as const;
export const CLOSEOUT_CONFIRMERS = ['organization', 'c3pao'] as const;

/** An ISO 8601 UTC timestamp with milliseconds, e.g. 2026-11-23T22:30:00.000Z. */
const isoNow = sql`(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))`;

/**
 * Text compared without case, so the unique index and every `email = ?` lookup treat
 * A@x.com and a@x.com as the same address.
 */
const nocaseText = customType<{ data: string }>({
  dataType: () => 'text COLLATE NOCASE',
});

export const assessment = sqliteTable(
  'assessment',
  {
    /** A UUID, generated by the api. */
    id: text('id').primaryKey(),
    type: text('type', { enum: ASSESSMENT_TYPES }).notNull().default('self'),
    /** YYYY-MM-DD, set when the assessment reaches Conditional status. */
    conditionalStatusDate: text('conditional_status_date'),
    /** `catalogKey(catalog)`, e.g. nist-800-171-r2@1.0.0. */
    catalogVersion: text('catalog_version').notNull(),
    createdAt: text('created_at').notNull().default(isoNow),
    updatedAt: text('updated_at').notNull().default(isoNow),
  },
  (table) => [check('assessment_type_check', sql`${table.type} in ('self', 'c3pao')`)],
);

/** People who sign in. Never deleted; `active = false` turns one off. */
export const user = sqliteTable(
  'user',
  {
    /** A UUID, generated by the api. */
    id: text('id').primaryKey(),
    /** Unique without case. The api stores it trimmed and lowercased. */
    email: nocaseText('email').notNull().unique('user_email_unique'),
    displayName: text('display_name').notNull(),
    role: text('role', { enum: ROLES }).notNull(),
    /** An Argon2id hash (`$argon2id$…`). Never returned, logged or audited. */
    passwordHash: text('password_hash').notNull(),
    active: integer('active', { mode: 'boolean' }).notNull().default(true),
    /** Consecutive failed sign-ins; reset by a success or when a lock ends. */
    failedSignIns: integer('failed_sign_ins').notNull().default(0),
    /** ISO timestamp; sign-in is refused while now < locked_until. */
    lockedUntil: text('locked_until'),
    createdAt: text('created_at').notNull().default(isoNow),
    updatedAt: text('updated_at').notNull().default(isoNow),
  },
  (table) => [
    check('user_role_check', sql`${table.role} in ('admin', 'contributor')`),
    check('user_active_check', sql`${table.active} in (0, 1)`),
  ],
);

/** Signed-in sessions. The cookie holds the token; only its SHA-256 is stored. */
export const session = sqliteTable(
  'session',
  {
    /** SHA-256 hex of the session token. */
    id: text('id').primaryKey(),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    csrfToken: text('csrf_token').notNull(),
    /** ISO timestamps from the api's clock (`buildApp({ now })`), so no default. */
    createdAt: text('created_at').notNull(),
    lastSeenAt: text('last_seen_at').notNull(),
  },
  (table) => [index('session_user_id_idx').on(table.userId)],
);

/**
 * Append-only history of every status or content change. Triggers (migration 0002) abort any
 * UPDATE or DELETE. Write rows only through `recordAudit` (src/audit/record.ts).
 */
export const auditEvent = sqliteTable(
  'audit_event',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    /** ISO timestamp from the api's clock. */
    at: text('at').notNull(),
    /** Null for events with no signed-in actor. */
    actorUserId: text('actor_user_id').references(() => user.id),
    assessmentId: text('assessment_id').references(() => assessment.id),
    action: text('action').notNull(),
    entityType: text('entity_type').notNull(),
    entityId: text('entity_id').notNull(),
    /** JSON of the changed fields before the change; null on create. */
    before: text('before'),
    /** JSON of the changed fields after the change. */
    after: text('after'),
    requestId: text('request_id'),
  },
  (table) => [index('audit_event_entity_idx').on(table.entityType, table.entityId, table.id)],
);

