/**
 * Versions of an evidence item, numbered 1, 2, 3… Either a stored file (contains_cui = 0: name,
 * size, SHA-256 and store key) or, for CUI, a reference to where the file really lives.
 */
export const evidenceVersion = sqliteTable(
  'evidence_version',
  {
    evidenceId: text('evidence_id')
      .notNull()
      .references(() => evidenceItem.id),
    version: integer('version').notNull(),
    containsCui: integer('contains_cui', { mode: 'boolean' }).notNull(),
    fileName: text('file_name'),
    /** Bytes. */
    size: integer('size'),
    /** Lowercase hex SHA-256 of the bytes. */
    sha256: text('sha256'),
    /** The evidence store key (`FileStore.put`). */
    storageKey: text('storage_key'),
    referenceLocation: text('reference_location'),
    referenceNote: text('reference_note'),
    createdBy: text('created_by')
      .notNull()
      .references(() => user.id),
    /** ISO timestamp from the api's clock. */
    createdAt: text('created_at').notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.evidenceId, table.version] }),
    check('evidence_version_version_check', sql`${table.version} >= 1`),
    check(
      'evidence_version_kind_check',
      sql`(${table.containsCui} = 0 and ${table.fileName} is not null and ${table.size} is not null
        and ${table.sha256} is not null and ${table.storageKey} is not null
        and length(${table.sha256}) = 64 and ${table.sha256} not glob '*[^0-9a-f]*'
        and ${table.size} >= 1
        and ${table.referenceLocation} is null and ${table.referenceNote} is null)
        or (${table.containsCui} = 1 and ${table.fileName} is null and ${table.size} is null
        and ${table.sha256} is null and ${table.storageKey} is null
        and ${table.referenceLocation} is not null)`,
    ),
  ],
);

